#!/usr/bin/env python3
"""Render results.json into TABLES.md (exact numbers quoted by REPORT.md)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def pick(rows, **kw):
    return [r for r in rows if all(abs(r[k] - v) < 1e-9 for k, v in kw.items())]


def pct(x):
    return "—" if x is None else f"{100 * x:.1f}%"


def main():
    r = json.loads((HERE / "results.json").read_text())
    g = r["grid_24_tasks"]
    L = ["# Power simulation tables (generated by make_tables.py)", "",
         f"reps={r['meta']['reps']}, bootstrap/sign-flip resamples={r['meta']['boots']}, logit task SD={r['meta']['sigma_logit']}, seed={r['meta']['seed']}. "
         "Monte-Carlo SE is at most 0.8 percentage points for these reps.", ""]
    cols = [("p_rule_pooled", "Rule (pooled ≥10 pp)"), ("p_rule_majority", "Rule (majority ≥10 pp)"), ("p_rule_seed42_only", "Rule (seed 42 only)"),
            ("p_mcnemar_majority", "McNemar"), ("p_sign_test", "Sign test"), ("p_signflip_permutation", "Sign-flip perm."),
            ("p_bootstrap_lower_gt0", "Bootstrap CI>0"), ("p_rule_pooled_and_signflip", "Rule AND sign-flip"), ("p_rule_pooled_and_ci", "Rule AND CI>0")]
    for seeds, rho in ((1, 0.0), (3, 0.0), (3, 0.5), (3, 0.9)):
        rows = pick(g, seeds=seeds, rho=rho)
        if not rows:
            continue
        avail = [c for c in cols if c[0] in rows[0]]
        L += [f"## 24 tasks, {seeds} seed(s), seed ICC {rho}", "",
              "| B base | True effect | " + " | ".join(c[1] for c in avail) + " | SD of pooled diff |",
              "|---:|---:|" + "---:|" * (len(avail) + 1)]
        for row in sorted(rows, key=lambda x: (x["base"], x["delta"])):
            L.append(f"| {pct(row['base'])} | +{100 * row['delta']:.0f} pp | " + " | ".join(pct(row[c[0]]) for c in avail)
                     + f" | {100 * row['pooled_diff_sd_mean' if 'pooled_diff_sd_mean' in row else 'pooled_diff_sd']:.1f} pp |")
        L.append("")
    L += ["## Tasks needed for 80% power (seed ICC 0.5)", "", "Smallest value on the grid 12/24/36/48/72/96/128/160/200/256/320/400/500 reaching ≥80%; '>500' if never.", "",
          "| B base | Effect | Seeds | Rule alone | McNemar | Sign test | Sign-flip | Bootstrap CI>0 | Rule AND sign-flip | Rule AND CI>0 |", "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for n in r["tasks_for_80_percent_power"]:
        f = lambda k: ">500" if n.get(k) is None else str(n[k])
        L.append(f"| {pct(n['base'])} | +{100 * n['delta']:.0f} pp | {n['seeds']} | {f('rule_pooled')} | {f('mcnemar_majority')} | {f('sign_test')} | {f('signflip_permutation')} | {f('bootstrap_lower_gt0')} | {f('rule_pooled_and_signflip')} | {f('rule_pooled_and_ci')} |")
    L += ["", "## Regression guard (12 tasks): probability C is rejected", "",
          "| Seeds | ICC | B pass rate | True harm | single seed ≤1 | majority ≤1 | pooled ≤1 | every seed ≤1 | majority ≤2 | majority ≤3 | pooled ≤2 |",
          "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for x in r["regression_guard"]:
        L.append(f"| {x['seeds']} | {x['rho']} | {pct(x['pass_rate'])} | {100 * x['harm']:.0f} pp | {pct(x['single_seed'])} | {pct(x['majority'])} | {pct(x['pooled_task_units'])} | "
                 f"{pct(x['every_seed'])} | {pct(x.get('majority_tol2'))} | {pct(x.get('majority_tol3'))} | {pct(x.get('pooled_tol2'))} |")
    L += ["", "## Sensitivity to task heterogeneity (B base 10%, 3 seeds, ICC 0.5)", "", "| logit SD | Effect | Rule pooled | Sign test | McNemar |", "|---:|---:|---:|---:|---:|"]
    for x in r["sigma_sensitivity"]:
        L.append(f"| {x['sigma']} | +{100 * x['delta']:.0f} pp | {pct(x['p_rule_pooled'])} | {pct(x['p_sign_test'])} | {pct(x['p_mcnemar_majority'])} |")
    L += ["", "## Graded secondary endpoint (4 fixed-input values per task, base ≈65%, 1 seed)", "", "| Tasks | Effect | Paired t | Sign test | Mean diff ≥10 pp |", "|---:|---:|---:|---:|---:|"]
    for x in r["graded_endpoint"]:
        L.append(f"| {x['n_tasks']} | +{100 * x['delta']:.0f} pp | {pct(x['p_paired_t'])} | {pct(x['p_sign_test'])} | {pct(x['p_mean_diff_ge_10pp'])} |")
    (HERE / "TABLES.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
